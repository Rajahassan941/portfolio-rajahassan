/**
 * Generates a tiny, tree-shaken icon registry from `simple-icons`.
 * Only the slugs listed below are emitted, so the 3k+ icon package never
 * reaches the client bundle.
 *
 * Usage: npm run icons
 */
import * as icons from "simple-icons";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const SLUGS = [
  "javascript", "typescript", "react", "nextdotjs", "redux", "reactquery",
  "reacttable", "mui", "tailwindcss", "html5", "css", "nodedotjs", "express",
  "jsonwebtokens", "socketdotio", "mongodb", "mysql", "git", "gitlab", "linux",
  "pm2", "nginx", "postman", "docker", "firebase", "vite", "fastapi", "sqlite",
  "github",
];

const toKey = (slug) => "si" + slug.charAt(0).toUpperCase() + slug.slice(1);

const out = {};
for (const slug of SLUGS) {
  const icon = icons[toKey(slug)];
  if (!icon) throw new Error(`simple-icons has no icon for "${slug}"`);
  out[slug] = { title: icon.title, hex: `#${icon.hex}`, path: icon.path };
}

const file = `// AUTO-GENERATED by scripts/generate-icons.mjs — do not edit by hand.
// Icons from simple-icons (CC0-1.0). Brand marks remain property of their owners.

export const SIMPLE_ICONS = ${JSON.stringify(out, null, 2)} as const;

export type SimpleIconSlug = keyof typeof SIMPLE_ICONS;
`;

const target = join(dirname(fileURLToPath(import.meta.url)), "../src/components/icons/simple-icons.generated.ts");
writeFileSync(target, file);
console.log(`Wrote ${SLUGS.length} icons -> ${target}`);
